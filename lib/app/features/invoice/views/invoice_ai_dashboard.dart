        ),
        const SizedBox(width: BauhausDesign.space3),
        Expanded(
          child: Column(
            children: [
              _buildStatCard(
                context,
                textTheme,
                title: 'GENERATED',
                value: '24',
                icon: Icons.auto_awesome,
                accentColor: BauhausDesign.success,
