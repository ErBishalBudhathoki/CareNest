  // ─── Stats Grid ──────────────────────────────────────────────────────
  Widget _buildStatsGrid(BuildContext context, TextTheme textTheme) {
    return Row(
      children: [
        Expanded(
          child: Column(
            children: [
              _buildStatCard(
